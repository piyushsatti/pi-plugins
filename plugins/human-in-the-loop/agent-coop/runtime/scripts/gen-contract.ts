// web/src/contract.gen.js, generated from src/contract (B2/CQ5).
//
// web/ used to hand-copy the contract's enums, and the drift was silent by
// construction: web/src/lib/sse.js listed eight of the nine SSE event names, so
// the browser never subscribed to `doc_added` and a document joining an open
// session updated nothing. Nothing failed; the feature was simply absent.
//
// A direct import would be the better answer, and it is not available: the
// contract is Zod schemas, so importing one value pulls zod into the browser
// bundle. So the values are EXTRACTED here — read off the schemas themselves,
// never retyped — into a plain JS module with no dependencies, which esbuild
// bundles like any other web source.
//
// The artifact is committed and checked: scripts/build.ts regenerates it, and
// tests/web/test_contract_gen.test.ts fails when the committed file and a fresh
// render disagree. That is what makes it an artifact rather than a second copy.
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import {
  ActorSchema,
  AnchorStateSchema,
  ChangeKindSchema,
  CommentStatusSchema,
  DeliverySchema,
  DiffBaseSchema,
  MAX_TEXT_LEN,
  MAX_TITLE_LEN,
  SSE_EVENT_NAMES,
  SessionStateSchema,
  contract_version,
} from "../src/contract/index.ts";

export const GENERATED_PATH = join(import.meta.dir, "..", "web", "src", "contract.gen.js");

/** One exported `const` per enum, in the contract's own order. */
// Only what web/ actually compares against. `DomainErrorCode` is deliberately
// absent: the codes never cross the wire (src/server/errors.ts turns them into a
// status and a message), so exporting them to the browser would advertise a
// value it can never receive.
const VALUES: Record<string, readonly string[]> = {
  SESSION_STATES: SessionStateSchema.options,
  ANCHOR_STATES: AnchorStateSchema.options,
  COMMENT_STATUSES: CommentStatusSchema.options,
  DELIVERY_MODES: DeliverySchema.options,
  ACTORS: ActorSchema.options,
  CHANGE_KINDS: ChangeKindSchema.options,
  DIFF_BASES: DiffBaseSchema.options,
  SSE_EVENT_NAMES: [...SSE_EVENT_NAMES],
};

/** The length caps a form control must state to a human (SEC-6). A `maxlength`
 *  attribute is the seam's cap seen by the user, so it is read off
 *  src/contract/limits.ts like everything else here, never typed twice. */
const NUMBERS: Record<string, number> = {
  MAX_TITLE_LEN,
  MAX_TEXT_LEN,
};

const HEADER = `// GENERATED by scripts/gen-contract.ts from src/contract — do not edit.
//
// The contract's enums as plain frozen arrays and its length caps as plain
// numbers, so web/ can import what it must otherwise hand-copy (B2/CQ5). Regenerate with \`bun run scripts/gen-contract.ts\`;
// scripts/build.ts does it on every build and tests/web/test_contract_gen.test.ts
// fails if this file and src/contract disagree.
//
// Values only. Nothing derived, nothing labelled, no logic: a label for a human
// belongs to the view that shows it, and putting one here would make this file a
// place decisions live rather than a projection of the contract.
`;

export function renderContractModule(): string {
  const lines = [HEADER, `export const CONTRACT_VERSION = ${JSON.stringify(contract_version)};`, ""];
  for (const [name, value] of Object.entries(NUMBERS)) {
    lines.push(`export const ${name} = ${value};`);
  }
  lines.push("");
  for (const [name, values] of Object.entries(VALUES)) {
    lines.push(`export const ${name} = Object.freeze([`);
    for (const v of values) lines.push(`  ${JSON.stringify(v)},`);
    lines.push("]);", "");
  }
  return lines.join("\n");
}

/** Writes the module. Returns true when the file on disk changed. */
export function generateContractModule(path = GENERATED_PATH): boolean {
  const next = renderContractModule();
  let current: string | null = null;
  try {
    current = readFileSync(path, "utf8");
  } catch {
    current = null; // not generated yet
  }
  if (current === next) return false;
  writeFileSync(path, next);
  return true;
}

if (import.meta.main) {
  const changed = generateContractModule();
  console.log(`${changed ? "wrote" : "unchanged"} ${GENERATED_PATH}`);
}
